-- v85: MCP Management module — CONSOLIDATED canonical v1.6 schema.
--
-- Merges the content of V48..V52 (MCP Management migrations) into a single
-- self-contained migration:
--   V48  : legacy stub (no-op) — nothing to carry over.
--   V49  : canonical v1.6 schema (design decisions Q-1..Q-57, REV3-01..18)
--          — DDL superseded by V51 (CHAR(1) type fix), comments kept below.
--   V50  : flag column type fix (archived_yn / deleted_yn / checksum_sha256
--          to VARCHAR) — already baked into the DDL below.
--   V51  : final self-contained schema (drop + recreate, correct types).
--   V52  : FR-MCP-023 (v1.24) MCP Rating & Subscribe (mcp_ratings,
--          mcp_subscriptions) — mirrors skill_ratings/skill_subscriptions.
--
-- Self-contained: drops any existing MCP tables (partial or complete, from
-- any prior state) and recreates them. Safe to run on any DB state: fresh,
-- partially migrated, or fully migrated.
--
-- v1.6 decisions applied (from V49 header):
--   Q-3   server_key: slugify from name, unique UNCONDITIONAL (incl. soft-deleted),
--         immutable forever, used as key in mcpServers config.
--   Q-8   version = auto-increment INTEGER (1, 2, 3 ...); no major.minor.patch.
--   Q-11  source enum: SKILL_MD (frontmatter of skill.md) | MANUAL (no MANIFEST).
--   Q-33  slugify: NFC normalize, lowercase, [a-z0-9]+, '-' sep, max 50,
--         fallback mcp-{id}.
--   Q-40  public_scope lives on mcp_version (editable in Update Version);
--         mcp_master.public_scope syncs from the newly approved version.
--   Q-41  Add MCP: scope stored on BOTH mcp_version (v1 DRAFT) and mcp_master
--         (synced immediately at creation, never NULL).
--   Q-47  server_key UNIQUE unconditional (never reused after soft delete).
--   Q-50  optimistic-lock counter renamed to lock_version (avoid confusion
--         with mcp_version / version_number).
--   Q-55  master.status stays APPROVED when rejecting a non-current version.
--   REV3-12  archived_reason VARCHAR(500), kept after Unarchive (audit trail).
--   Q-21  notification_dead_letter table for 3-retry exponential backoff.
--   Q-4   Guide merged into Description (no separate guide_web column).
--   Q-10  Archive is master-level flag (archived_yn), NOT a version status enum.
--   FR-MCP-023  Rating: 1 user 1 rating per MCP (1.0-5.0, step 0.5, upsert
--         on re-rate). Subscribe: follow an APPROVED MCP to receive
--         new-approved-version notifications.

-- ============================================================
-- 0. Drop all MCP tables (IF EXISTS = safe on any state)
-- ============================================================

DROP TABLE IF EXISTS mcp_subscriptions CASCADE;
DROP TABLE IF EXISTS mcp_ratings CASCADE;
DROP TABLE IF EXISTS skill_mcp_dependency CASCADE;
DROP TABLE IF EXISTS mcp_download_log CASCADE;
DROP TABLE IF EXISTS mcp_view_log CASCADE;
DROP TABLE IF EXISTS mcp_status_history CASCADE;
DROP TABLE IF EXISTS mcp_version_file CASCADE;
DROP TABLE IF EXISTS mcp_version CASCADE;
DROP TABLE IF EXISTS mcp_master CASCADE;
DROP TABLE IF EXISTS notification_dead_letter CASCADE;

-- ============================================================
-- 1. MCP MASTER
-- ============================================================
--
-- mcp_code  : PA-2 sequential short id (e.g. MCP-0001), unique across store,
--             never reused after soft delete (Q-2).
-- server_key: human-readable key in AI client config (~/.aipro/mcp.json),
--             slugified from mcp_name at creation, immutable forever (Q-3),
--             UNIQUE UNCONDITIONAL — kept unique even for soft-deleted rows
--             so FK skill_mcp_dependency.server_key never breaks (Q-47).
-- current_version : INTEGER version number of the live APPROVED version;
--                   NULL until the first APPROVED version exists (Q-8).
-- transport  : denormalized from the current version for grid/filter; the
--              service keeps it in sync on approval.
-- public_scope : synced from the current version's public_scope on approval
--                (Q-40/Q-41); set immediately at Add MCP so DRAFT visibility
--                applies scope rules.
-- lock_version : optimistic-lock counter (409 CONCURRENT_UPDATE_CONFLICT) (Q-50).
-- archived_* : master-level archive flag (Q-10). archived_reason is kept
--              after Unarchive for audit trail (REV3-12).
-- Note: description lives on mcp_version (version-level), NOT on master (Q-4:
-- Guide merged into Description; master has no description column).

CREATE TABLE mcp_master (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mcp_code          VARCHAR(100) NOT NULL,
    mcp_name          VARCHAR(200) NOT NULL,
    server_key        VARCHAR(100) NOT NULL,
    tags              JSONB,
    status            VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED')),
    public_scope      VARCHAR(20) NOT NULL DEFAULT 'PRIVATE'
                        CHECK (public_scope IN ('PRIVATE', 'PART', 'GROUP', 'PUBLIC')),
    transport         VARCHAR(20) NOT NULL CHECK (transport IN ('HTTP', 'STDIO')),
    current_version   INT,
    archived_yn       VARCHAR(1) NOT NULL DEFAULT 'N' CHECK (archived_yn IN ('Y', 'N')),
    archived_by       BIGINT REFERENCES "user"(id),
    archived_at       TIMESTAMP WITH TIME ZONE,
    archived_reason   VARCHAR(500),
    view_count        INT NOT NULL DEFAULT 0,
    lock_version      INT NOT NULL DEFAULT 1,
    deleted_yn        VARCHAR(1) NOT NULL DEFAULT 'N' CHECK (deleted_yn IN ('Y', 'N')),
    created_by        BIGINT NOT NULL REFERENCES "user"(id),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_ip        VARCHAR(45),
    updated_by        BIGINT REFERENCES "user"(id),
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_ip        VARCHAR(45)
);

CREATE UNIQUE INDEX uk_mcp_code ON mcp_master (mcp_code);
CREATE UNIQUE INDEX uk_mcp_server_key ON mcp_master (server_key);
CREATE INDEX idx_mcp_created_by ON mcp_master (created_by);
CREATE INDEX idx_mcp_status ON mcp_master (status);
CREATE INDEX idx_mcp_scope ON mcp_master (public_scope);
CREATE INDEX idx_mcp_transport ON mcp_master (transport);
CREATE INDEX idx_mcp_archived ON mcp_master (archived_yn);
CREATE INDEX idx_mcp_created_at ON mcp_master (created_at DESC);

-- ============================================================
-- 2. MCP VERSION
-- ============================================================
--
-- Each version is an immutable content snapshot once APPROVED (BR-08).
-- version_number : auto-increment INTEGER per MCP (1, 2, 3 ...) (Q-8).
-- status         : DRAFT | PENDING_APPROVAL | APPROVED | REJECTED.
--                  Archive is a master-level flag, NOT a version status (Q-10).
-- config_template   : canonical mcpServers entry with {{PLACEHOLDER}}s
--                     (web never stores real credentials — BR-02).
-- prerequisites     : { runtime{name,version}, internalServices[{name,url}] }
--                     (OS/Architecture dropped from form — Q-5: V1 fixed Win x64).
-- credential_fields : [{ key, label, inputType, required, help }] — declaration
--                     only, no real values (BR-02, D-8). Auto-generated from
--                     placeholders in config.
-- description       : rich text (Guide merged in — Q-4). Sanitized (appendix A).
-- public_scope      : scope at version level (Q-40); master syncs on approval.
-- lock_version      : optimistic-lock counter for edits (409 conflict) (Q-50).
-- rejection_reason  : populated when status = REJECTED (required, <=500 chars).

CREATE TABLE mcp_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mcp_id            BIGINT NOT NULL REFERENCES mcp_master(id),
    version_number    INT NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
                        CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED')),
    transport         VARCHAR(20) NOT NULL CHECK (transport IN ('HTTP', 'STDIO')),
    config_template   JSONB NOT NULL,
    prerequisites     JSONB NOT NULL,
    credential_fields JSONB NOT NULL,
    description       TEXT,
    changelog         TEXT,
    rejection_reason  TEXT CHECK (char_length(rejection_reason) <= 500),
    public_scope      VARCHAR(20) NOT NULL DEFAULT 'PRIVATE'
                        CHECK (public_scope IN ('PRIVATE', 'PART', 'GROUP', 'PUBLIC')),
    lock_version      INT NOT NULL DEFAULT 1,
    created_by        BIGINT NOT NULL REFERENCES "user"(id),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_by      BIGINT REFERENCES "user"(id),
    submitted_at      TIMESTAMP WITH TIME ZONE,
    approved_by       BIGINT REFERENCES "user"(id),
    approved_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_mcp_version UNIQUE (mcp_id, version_number)
);

CREATE INDEX idx_mcp_version_mcp ON mcp_version (mcp_id, version_number DESC);
CREATE INDEX idx_mcp_version_status ON mcp_version (status);

-- ============================================================
-- 3. MCP VERSION FILE
-- ============================================================
--
-- One version can have several files (PACKAGE for STDIO, CONFIG, DOCUMENT).
-- file_path is the internal storage path — never exposed via API (BR-02).
-- checksum_sha256 is computed on upload (always present).
-- Retention (Q-14): APPROVED version files kept forever; DRAFT/PENDING/REJECTED
-- purged after 30 days (enforced by a scheduled job, not schema).

CREATE TABLE mcp_version_file (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mcp_version_id    BIGINT NOT NULL REFERENCES mcp_version(id) ON DELETE CASCADE,
    file_role         VARCHAR(20) NOT NULL CHECK (file_role IN ('PACKAGE', 'CONFIG', 'DOCUMENT')),
    file_name         VARCHAR(255) NOT NULL,
    file_path         VARCHAR(500) NOT NULL,
    file_size         BIGINT NOT NULL,
    checksum_sha256   VARCHAR(64) NOT NULL,
    uploaded_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_mcp_file_version ON mcp_version_file (mcp_version_id);

-- ============================================================
-- 4. MCP STATUS HISTORY
-- ============================================================
--
-- Audit trail of workflow transitions (who, when, from -> to, reason).
-- Mirrors skill_status_history; kept module-local by design.
-- ISS-16: mcp_status_history is sufficient audit for V1 (no separate audit log).

CREATE TABLE mcp_status_history (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mcp_id            BIGINT NOT NULL REFERENCES mcp_master(id),
    mcp_version_id    BIGINT REFERENCES mcp_version(id),
    from_status       VARCHAR(20),
    to_status         VARCHAR(20) NOT NULL,
    changed_by        BIGINT NOT NULL REFERENCES "user"(id),
    rejection_reason  TEXT CHECK (char_length(rejection_reason) <= 500),
    changed_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_mcp_status_history_mcp ON mcp_status_history (mcp_id);
CREATE INDEX idx_mcp_status_history_changed_at ON mcp_status_history (changed_at DESC);

-- ============================================================
-- 5. SKILL MCP DEPENDENCY
-- ============================================================
--
-- Join table owned by the MCP module. FK points INTO skills_master; the
-- skill schema is untouched. A skill pins an EXACT mcp_version (BR-04).
-- UNIQUE (skill_id, mcp_id) prevents the same MCP twice on one skill (SRS §8.2).
-- Dependencies are editable only while the skill is DRAFT/REJECTED
-- (same rule as Edit Skill); APPROVED skills change MCPs via a new skill version.
--
-- source: SKILL_MD (declared in frontmatter of skill.md — Q-11) | MANUAL.
-- mcp_server_key: denormalized for frontmatter matching + display (Q-3).
-- mcp_version_number: pinned INTEGER version (Q-8).

CREATE TABLE skill_mcp_dependency (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id            BIGINT NOT NULL REFERENCES skills_master(id) ON DELETE CASCADE,
    mcp_id              BIGINT NOT NULL REFERENCES mcp_master(id),
    mcp_code            VARCHAR(100) NOT NULL,
    mcp_server_key      VARCHAR(100) NOT NULL,
    mcp_version_number  INT NOT NULL,
    required            BOOLEAN NOT NULL DEFAULT TRUE,
    source              VARCHAR(20) NOT NULL CHECK (source IN ('SKILL_MD', 'MANUAL')),
    CONSTRAINT uq_skill_mcp_dependency UNIQUE (skill_id, mcp_id)
);

CREATE INDEX idx_skill_mcp_dep_mcp ON skill_mcp_dependency (mcp_id);
CREATE INDEX idx_skill_mcp_dep_skill ON skill_mcp_dependency (skill_id);

-- ============================================================
-- 6. MCP VIEW LOG
-- ============================================================
--
-- Idempotent view count: one user counts once per MCP per 15 minutes
-- (configurable via app.mcp.view-window-minutes, default 15 — syncs with
-- Skill Management; supersedes baseline §11.6 "24h").

CREATE TABLE mcp_view_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mcp_id     BIGINT NOT NULL REFERENCES mcp_master(id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    viewed_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_mcp_view_log_mcp_user ON mcp_view_log (mcp_id, user_id);
CREATE INDEX idx_mcp_view_log_viewed_at ON mcp_view_log (viewed_at DESC);

-- ============================================================
-- 7. MCP DOWNLOAD LOG
-- ============================================================
--
-- One row per file download event (web download; the app uses the same
-- file endpoint). No FK to version/file with ON DELETE CASCADE so history
-- survives version/file rows being cleaned up.

CREATE TABLE mcp_download_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mcp_id          BIGINT NOT NULL REFERENCES mcp_master(id),
    mcp_version_id  BIGINT REFERENCES mcp_version(id),
    file_id         BIGINT REFERENCES mcp_version_file(id),
    user_id         BIGINT NOT NULL REFERENCES "user"(id),
    downloaded_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_mcp_download_log_mcp_time ON mcp_download_log (mcp_id, downloaded_at);

-- ============================================================
-- 8. NOTIFICATION DEAD LETTER  (Q-21 / FR-MCP-022)
-- ============================================================
--
-- In-app notifications that failed delivery after 3 retries (exponential
-- backoff 1s, 4s, 16s) land here. Admin can view + manually retry or mark
-- resolved via the Admin Notification Dead Letter Viewer (FR-MCP-022).
-- Retention: 90 days (sync with log retention ISSUE-27).

CREATE TABLE notification_dead_letter (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_type   VARCHAR(50) NOT NULL
                            CHECK (notification_type IN
                                   ('MCP_ARCHIVE', 'MCP_SCOPE_CHANGE', 'SKILL_BLOCKED')),
    recipient_user_id   BIGINT NOT NULL REFERENCES "user"(id),
    payload             JSONB NOT NULL,
    error_message       TEXT,
    retry_count         INT NOT NULL DEFAULT 0,
    status              VARCHAR(20) NOT NULL DEFAULT 'PENDING_RETRY'
                            CHECK (status IN ('PENDING_RETRY', 'RESOLVED')),
    last_retry_at       TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notif_dl_status ON notification_dead_letter (status);
CREATE INDEX idx_notif_dl_type ON notification_dead_letter (notification_type);
CREATE INDEX idx_notif_dl_created_at ON notification_dead_letter (created_at DESC);
CREATE INDEX idx_notif_dl_recipient ON notification_dead_letter (recipient_user_id);

-- ============================================================
-- 9. NOTIFICATIONS DEEP-LINK
-- ============================================================
--
-- mcp_id: the MCP a notification refers to (owner-stuck-draft D-20,
-- archive/scope-change BR-06). Same pattern as skill_id / request_id /
-- news_id deep-link columns. IF NOT EXISTS keeps this migration
-- self-contained for fresh installs.

ALTER TABLE notifications ADD COLUMN IF NOT EXISTS mcp_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_notifications_mcp ON notifications (mcp_id);

-- ============================================================
-- 10. MCP RATINGS  (FR-MCP-023, merged from V52)
-- ============================================================
--
-- 1 user 1 rating per MCP (1.0-5.0, step 0.5, upsert on re-rate).
-- Mirrors skill_ratings (V15).

CREATE TABLE mcp_ratings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mcp_id     BIGINT NOT NULL REFERENCES mcp_master(id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    rating     NUMERIC(2,1) NOT NULL CHECK (rating BETWEEN 1.0 AND 5.0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (mcp_id, user_id)
);

CREATE INDEX idx_mcp_rating_mcp ON mcp_ratings (mcp_id);

-- ============================================================
-- 11. MCP SUBSCRIPTIONS  (FR-MCP-023, merged from V52)
-- ============================================================
--
-- Follow an APPROVED MCP to receive new-approved-version notifications.
-- Mirrors skill_subscriptions (V15).

CREATE TABLE mcp_subscriptions (
    mcp_id     BIGINT NOT NULL REFERENCES mcp_master(id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (mcp_id, user_id)
);

CREATE INDEX idx_mcp_subscription_user ON mcp_subscriptions (user_id);
