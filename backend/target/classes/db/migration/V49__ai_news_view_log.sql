-- AI News view log: one row per (news, user) — a user counts once per
-- news item (the frontend fires the call after 30s of reading the detail).
-- "How many users viewed each news" = COUNT(*) per news_id.
-- "Which users viewed which news" = the rows themselves.
-- The unique (news_id, user_id) constraint doubles as the news_id index
-- (B-tree prefix), so no standalone news_id index is needed.
CREATE TABLE ai_news_view_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    news_id     BIGINT NOT NULL REFERENCES ai_news(news_id),
    user_id     BIGINT NOT NULL REFERENCES "user"(id),
    viewed_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ai_news_view_log UNIQUE (news_id, user_id)
);

-- Denormalized distinct-viewer counter on ai_news (same pattern as
-- skills_master.view_count), read by the detail endpoint.
ALTER TABLE ai_news ADD COLUMN view_count INTEGER NOT NULL DEFAULT 0;
