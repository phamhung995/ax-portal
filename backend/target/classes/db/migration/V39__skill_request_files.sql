-- Flyway migration V39: file attachments for skill requests.
--
-- A skill request post can carry image and non-image attachments.
-- Physical files live on disk under uploads/skill-requests/{requestId}/
-- (uuid-prefixed names); only metadata is stored here.

CREATE TABLE skill_request_files (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES skill_requests(id) ON DELETE CASCADE,
    file_name  VARCHAR(255) NOT NULL,
    file_path  VARCHAR(500) NOT NULL,
    file_size  BIGINT,
    is_image   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_request_file_request ON skill_request_files (request_id);
