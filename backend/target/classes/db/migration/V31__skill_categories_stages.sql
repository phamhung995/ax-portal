-- Flyway migration V31: Skill categories & process stages
-- PostgreSQL 17 compatible
--
-- 1 skill : N categories, 1 skill : N process stages (join tables).
-- Categories and stages are admin-managed master data.
-- Stages keep their pipeline order via sort_order.

CREATE TABLE skill_category (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_skill_category_name ON skill_category (lower(name));

CREATE TABLE process_stage (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_process_stage_name ON process_stage (lower(name));

CREATE TABLE skill_category_mapping (
    skill_id    BIGINT NOT NULL REFERENCES skills_master(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES skill_category(id) ON DELETE CASCADE,
    PRIMARY KEY (skill_id, category_id)
);
CREATE INDEX idx_scm_category ON skill_category_mapping (category_id);

CREATE TABLE skill_stage_mapping (
    skill_id BIGINT NOT NULL REFERENCES skills_master(id) ON DELETE CASCADE,
    stage_id BIGINT NOT NULL REFERENCES process_stage(id) ON DELETE CASCADE,
    PRIMARY KEY (skill_id, stage_id)
);
CREATE INDEX idx_ssm_stage ON skill_stage_mapping (stage_id);

