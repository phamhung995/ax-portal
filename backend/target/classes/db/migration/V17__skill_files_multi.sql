-- Flyway migration V17: multi-file support for skills.
--
-- A skill can now have multiple attached files. File metadata moves out of
-- skills_master (file_name/file_path/file_size) into a new skill_files table.
-- Existing single-file rows are migrated before the old columns are dropped.

CREATE TABLE skill_files (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id   BIGINT NOT NULL REFERENCES skills_master(id),
    file_name  VARCHAR(255) NOT NULL,
    file_path  VARCHAR(500) NOT NULL,
    file_size  BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_file_skill ON skill_files (skill_id);

-- Migrate the existing single file (if any) into skill_files.
INSERT INTO skill_files (skill_id, file_name, file_path, file_size)
SELECT id, file_name, file_path, file_size
FROM skills_master
WHERE file_path IS NOT NULL;

ALTER TABLE skills_master DROP COLUMN file_name;
ALTER TABLE skills_master DROP COLUMN file_path;
ALTER TABLE skills_master DROP COLUMN file_size;
