-- Skill download log: one row per download event (single file or zip,
-- current or snapshotted version). Pending-version previews are NOT logged.
-- Chart "Total downloads" metric counts only download_all rows by
-- non-creator users (filtered in HomeServiceImpl, not here).
CREATE TABLE skill_download_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id      BIGINT NOT NULL REFERENCES skills_master(id),
    user_id       BIGINT NOT NULL REFERENCES "user"(id),
    download_all  BOOLEAN NOT NULL DEFAULT FALSE,
    downloaded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_download_log_skill_time
    ON skill_download_log (skill_id, downloaded_at);
