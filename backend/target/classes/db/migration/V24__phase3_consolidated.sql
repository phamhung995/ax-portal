-- ============================================================
-- 3. Feedback (VOC)
-- ============================================================
--
-- User feedback: bug report / suggestion / question. Any authenticated user
-- can submit; admins manage it. Screenshot is stored as a base64 data URI
-- (same approach as skill description images).
-- Content is rich text (HTML) in a TEXT column with NO length limit
-- (the 1000-char limit is enforced client-side on stripped text only).

CREATE TABLE feedback (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES "user"(id),
    type            VARCHAR(20) NOT NULL CHECK (type IN ('BUG', 'SUGGESTION', 'QUESTION')),
    content         TEXT NOT NULL,
    screenshot      TEXT,
    page_url        VARCHAR(500),
    status          VARCHAR(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'IN_REVIEW', 'RESOLVED', 'IGNORED')),
    resolution_note VARCHAR(500),
    resolved_by     BIGINT REFERENCES "user"(id),
    resolved_at     TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_feedback_status ON feedback (status);
CREATE INDEX idx_feedback_user ON feedback (user_id);
CREATE INDEX idx_feedback_created ON feedback (created_at);

-- Deep-link: when a feedback is resolved/ignored, the creator receives a
-- notification; the bell needs the feedback id to open the detail popup.
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS feedback_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_notifications_feedback ON notifications (feedback_id);

-- ============================================================
-- 4. Skill categories & process stages
-- ============================================================
--
-- 1 skill : N categories, 1 skill : N process stages (join tables).
-- Categories and stages are admin-managed master data.
-- Stages keep their pipeline order via sort_order.

CREATE TABLE skill_category (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_skill_category_name ON skill_category (lower(name));

CREATE TABLE process_stage (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL,
    sort_order  INT NOT NULL DEFAULT 0,
    description VARCHAR(200),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_process_stage_name ON process_stage (lower(name));

CREATE TABLE skill_category_mapping (
    skill_id    BIGINT NOT NULL REFERENCES skills_master(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES skill_category(id) ON DELETE CASCADE,
    PRIMARY KEY (skill_id, category_id)
);
CREATE INDEX idx_scm_category ON skill_category_mapping (category_id);

CREATE TABLE skill_stage_mapping (
    skill_id BIGINT NOT NULL REFERENCES skills_master(id) ON DELETE CASCADE,
    stage_id BIGINT NOT NULL REFERENCES process_stage(id) ON DELETE CASCADE,
    PRIMARY KEY (skill_id, stage_id)
);
CREATE INDEX idx_ssm_stage ON skill_stage_mapping (stage_id);

