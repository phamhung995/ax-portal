-- ============================================================
-- 1. Skill Request Management (feed)
-- ============================================================
--
-- Skill requests are ideas/suggestions for skills that do not exist yet.
-- A request is public immediately after creation (no status/review).
-- The community votes and comments (brainstorm); a comment may link to an
-- existing skill and the request creator can mark such a comment as resolved.
--
-- Rules:
--   - title is NOT unique: several users may propose the same idea.
--   - no soft delete: nobody (not even admin) can delete a request.
--   - no status history table: transitions are not audited.

CREATE TABLE skill_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(100) NOT NULL,
    description     TEXT,
    hashtags        JSONB,
    vote_count      INT NOT NULL DEFAULT 0,
    comment_count   INT NOT NULL DEFAULT 0,
    created_by      BIGINT NOT NULL REFERENCES "user"(id),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_request_created_by ON skill_requests(created_by);

-- One vote per user (toggle: vote/unvote).
CREATE TABLE skill_request_votes (
    request_id BIGINT NOT NULL REFERENCES skill_requests(id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (request_id, user_id)
);

CREATE INDEX idx_skill_request_vote_user ON skill_request_votes(user_id);

CREATE TABLE skill_request_comments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      BIGINT NOT NULL REFERENCES skill_requests(id),
    user_id         BIGINT NOT NULL REFERENCES "user"(id),
    content         TEXT NOT NULL CHECK (char_length(content) <= 1000),
    linked_skill_id BIGINT NULL REFERENCES skills_master(id),
    resolved_yn     VARCHAR(1) NOT NULL DEFAULT 'N'
                         CHECK (resolved_yn IN ('N', 'Y')),
    resolved_at     TIMESTAMP WITH TIME ZONE,
    resolved_by     BIGINT NULL REFERENCES "user"(id),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at      TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_skill_request_comment_req ON skill_request_comments(request_id);
CREATE INDEX idx_skill_request_comment_skill ON skill_request_comments(linked_skill_id);

-- ============================================================
-- 2. AI News module
--    (SRS: ai-news/AI_News_Batch.md §6 + AI_News_Screen_SRS.md §6)
-- ============================================================

CREATE TABLE ai_news (
    news_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id     VARCHAR(320) NOT NULL UNIQUE,
    title          VARCHAR(200) NOT NULL,
    body           TEXT,
    sender         VARCHAR(320),
    source         VARCHAR(100) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    archive_yn     VARCHAR(1) NOT NULL DEFAULT 'N' CHECK (archive_yn IN ('Y', 'N')),
    imported_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX idx_ai_news_created ON ai_news (created_at DESC);

CREATE TABLE ai_news_source (
    source_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mailbox               VARCHAR(200) NOT NULL UNIQUE,
    imap_host             VARCHAR(200) NOT NULL,
    imap_port             SMALLINT NOT NULL DEFAULT 993,
    secret_ref            VARCHAR(200) NOT NULL,
    display_name          VARCHAR(100) NOT NULL,
    status                VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    last_success_run_at   TIMESTAMP WITH TIME ZONE,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE ai_news_batch_log (
    run_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at       TIMESTAMP WITH TIME ZONE,
    status            VARCHAR(10) NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'PARTIAL', 'FAILED', 'SKIPPED')),
    total_fetched     INT NOT NULL DEFAULT 0,
    total_inserted    INT NOT NULL DEFAULT 0,
    total_skipped     INT NOT NULL DEFAULT 0,
    total_failed      INT NOT NULL DEFAULT 0,
    total_archived    INT NOT NULL DEFAULT 0,
    error_message     TEXT,
    trigger_type      VARCHAR(10) NOT NULL DEFAULT 'CRON' CHECK (trigger_type IN ('CRON', 'MANUAL'))
);

CREATE TABLE ai_news_comment (
    comment_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    news_id       BIGINT NOT NULL REFERENCES ai_news(news_id),
    user_id       BIGINT NOT NULL REFERENCES "user"(id),
    parent_id     BIGINT REFERENCES ai_news_comment(comment_id),
    content       VARCHAR(1000) NOT NULL,
    helpful_count INT NOT NULL DEFAULT 0,
    reply_count   INT NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_ai_news_comment_news ON ai_news_comment (news_id, created_at DESC);

CREATE TABLE ai_news_comment_vote (
    comment_id BIGINT NOT NULL REFERENCES ai_news_comment(comment_id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (comment_id, user_id)
);

CREATE TABLE ai_news_like (
    news_id    BIGINT NOT NULL REFERENCES ai_news(news_id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (news_id, user_id)
);

