-- Flyway migration V72: skill share (Share Project feature).
--
-- A PROJECT-scope skill can be shared beyond its natural audience:
--   USER    -> one specific user (user_id set, project_key null)
--   PROJECT -> everyone in one project (project_key set, user_id null)
-- Shared users and shared-project members see the skill in addition to the
-- normal PROJECT scope audience. Only the creator or an admin may share.

CREATE TABLE skill_share (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL,
    share_type VARCHAR(10) NOT NULL,
    user_id BIGINT,
    project_key VARCHAR(100),
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_skill_share_skill
        FOREIGN KEY (skill_id) REFERENCES skills_master (id) ON DELETE CASCADE,
    CONSTRAINT skill_share_type_check
        CHECK (share_type IN ('USER', 'PROJECT')),
    CONSTRAINT skill_share_payload_check
        CHECK ((share_type = 'USER' AND user_id IS NOT NULL AND project_key IS NULL)
            OR (share_type = 'PROJECT' AND project_key IS NOT NULL AND user_id IS NULL))
);

CREATE INDEX idx_skill_share_skill ON skill_share (skill_id);
CREATE INDEX idx_skill_share_user ON skill_share (user_id);
CREATE INDEX idx_skill_share_project ON skill_share (project_key);
