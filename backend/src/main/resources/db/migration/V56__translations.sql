-- Multi-language (i18n) tables + seed (en/vi/ko).
-- Existing keys migrated from frontend features/home/i18n.ts and features/ai-news/i18n.ts.

CREATE TABLE translation_keys (
    id BIGSERIAL PRIMARY KEY,
    key VARCHAR(120) NOT NULL UNIQUE,
    description VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE translations (
    key_id BIGINT NOT NULL REFERENCES translation_keys(id) ON DELETE CASCADE,
    language VARCHAR(5) NOT NULL,
    value VARCHAR(1000) NOT NULL,
    updated_by BIGINT,
    updated_at TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (key_id, language)
);

CREATE INDEX idx_translations_language ON translations(language);

