-- Flyway migration V45: AI Tools module.
--
-- Independent module (separate from Skill Management): admin-only upload,
-- no status/scope/rating/subscription/version tracking. Categories and
-- process stages are SHARED with Skill Management (skill_category,
-- process_stage). One file per tool.

CREATE TABLE ai_tools (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(200) NOT NULL,
    description  TEXT,
    tags         JSONB,
    deleted_yn   VARCHAR(1) NOT NULL DEFAULT 'N' CHECK (deleted_yn IN ('Y', 'N')),
    created_by   BIGINT NOT NULL REFERENCES "user"(id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_tool_created_by ON ai_tools (created_by);
CREATE INDEX idx_ai_tool_updated_at ON ai_tools (updated_at);

CREATE TABLE ai_tool_category_mapping (
    tool_id     BIGINT NOT NULL REFERENCES ai_tools(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES skill_category(id) ON DELETE CASCADE,
    PRIMARY KEY (tool_id, category_id)
);
CREATE INDEX idx_atcm_category ON ai_tool_category_mapping (category_id);

CREATE TABLE ai_tool_stage_mapping (
    tool_id  BIGINT NOT NULL REFERENCES ai_tools(id) ON DELETE CASCADE,
    stage_id BIGINT NOT NULL REFERENCES process_stage(id) ON DELETE CASCADE,
    PRIMARY KEY (tool_id, stage_id)
);
CREATE INDEX idx_atsm_stage ON ai_tool_stage_mapping (stage_id);

CREATE TABLE ai_tool_files (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_id    BIGINT NOT NULL REFERENCES ai_tools(id) ON DELETE CASCADE,
    file_name  VARCHAR(255) NOT NULL,
    file_path  VARCHAR(500) NOT NULL,
    file_size  BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ai_tool_file_tool ON ai_tool_files (tool_id);

CREATE TABLE ai_tool_download_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_id       BIGINT NOT NULL REFERENCES ai_tools(id) ON DELETE CASCADE,
    user_id       BIGINT NOT NULL REFERENCES "user"(id),
    downloaded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ai_tool_download_log_tool_time
    ON ai_tool_download_log (tool_id, downloaded_at);
