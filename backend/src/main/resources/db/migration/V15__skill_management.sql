-- Flyway migration V15: Skill Management module (SRS 1. Skill Management module)
--
-- Step 0: drop the legacy skill-store tables from V5. They belong to an older
-- design (skill store: categories, versions, usage/impact tracking, security
-- scan) and are referenced by NO code (no JPA entity, no query, no frontend
-- usage). The new SRS defines a different model.
--
-- Step 1: create the SRS tables:
--   skills_master, skill_ratings, skill_comments, skill_status_history,
--   skill_subscriptions, skill_view_log

-- ---------------------------------------------------------------------
-- Step 0: drop legacy tables (child tables first)
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS audit_log;
DROP TABLE IF EXISTS skill_approval;
DROP TABLE IF EXISTS impact_record;
DROP TABLE IF EXISTS skill_usage;
DROP TABLE IF EXISTS skill_review;
DROP TABLE IF EXISTS skill_rating;
DROP TABLE IF EXISTS skill_version;
DROP TABLE IF EXISTS skill_tag_mapping;
DROP TABLE IF EXISTS skill_tag;
DROP TABLE IF EXISTS skill_category_mapping;
DROP TABLE IF EXISTS skill_category;
DROP TABLE IF EXISTS skill;

-- ---------------------------------------------------------------------
-- Step 1: new schema
-- ---------------------------------------------------------------------
CREATE TABLE skills_master (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    description       TEXT,
    approval_status   VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
                        CHECK (approval_status IN ('DRAFT', 'PENDING_APPROVAL', 'PUBLISHED', 'REJECTED')),
    public_scope      VARCHAR(20) NOT NULL DEFAULT 'PRIVATE'
                        CHECK (public_scope IN ('PRIVATE', 'PART', 'GROUP', 'PUBLIC')),
    rejection_reason  TEXT CHECK (char_length(rejection_reason) <= 500),
    hashtags          JSONB,
    file_name         VARCHAR(255),
    file_path         VARCHAR(500),
    file_size         BIGINT,
    view_count        INT NOT NULL DEFAULT 0,
    version           INT NOT NULL DEFAULT 1,
    deleted_yn        CHAR(1) NOT NULL DEFAULT 'N' CHECK (deleted_yn IN ('Y', 'N')),
    created_by        BIGINT NOT NULL REFERENCES "user"(id),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Case-insensitive unique skill name (global).
CREATE UNIQUE INDEX uk_skill_name_ci ON skills_master (LOWER(name));
CREATE INDEX idx_skill_created_by ON skills_master (created_by);
CREATE INDEX idx_skill_status ON skills_master (approval_status);
CREATE INDEX idx_skill_scope ON skills_master (public_scope);
CREATE INDEX idx_skill_updated_at ON skills_master (updated_at);

CREATE TABLE skill_ratings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id   BIGINT NOT NULL REFERENCES skills_master(id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    rating     NUMERIC(2,1) NOT NULL CHECK (rating BETWEEN 1.0 AND 5.0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (skill_id, user_id)
);

CREATE INDEX idx_skill_rating_skill ON skill_ratings (skill_id);

CREATE TABLE skill_comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id   BIGINT NOT NULL REFERENCES skills_master(id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    content    TEXT NOT NULL CHECK (char_length(content) <= 1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_skill_comment_skill ON skill_comments (skill_id);

-- Audit trail for workflow status transitions (who, when, from -> to, reason).
CREATE TABLE skill_status_history (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id          BIGINT NOT NULL REFERENCES skills_master(id),
    from_status       VARCHAR(20),
    to_status         VARCHAR(20) NOT NULL,
    changed_by        BIGINT NOT NULL REFERENCES "user"(id),
    rejection_reason  TEXT CHECK (char_length(rejection_reason) <= 500),
    changed_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_status_history_skill ON skill_status_history (skill_id);

-- Subscribe: follow a PUBLISHED skill for new-version notifications.
CREATE TABLE skill_subscriptions (
    skill_id   BIGINT NOT NULL REFERENCES skills_master(id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (skill_id, user_id)
);

CREATE INDEX idx_skill_subscription_user ON skill_subscriptions (user_id);

-- Idempotent view count: one user counts once per skill per 24h.
CREATE TABLE skill_view_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id   BIGINT NOT NULL REFERENCES skills_master(id),
    user_id    BIGINT NOT NULL REFERENCES "user"(id),
    viewed_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_view_log_skill_user ON skill_view_log (skill_id, user_id);
