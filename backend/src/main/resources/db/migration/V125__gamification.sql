-- V125: Gamification — points ledger, daily check-in, perk catalog.
-- Points and reputation are SEPARATE currencies (decided 2026-11-16):
-- points buy utilities/status, never trust privileges.
-- Every points movement is one row in points_transactions (the ledger);
-- user_points.balance is the cached sum, updated in the same transaction.

CREATE TABLE user_points (
    user_id    BIGINT PRIMARY KEY REFERENCES "user"(id),
    balance    INT NOT NULL DEFAULT 0 CHECK (balance >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE points_transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES "user"(id),
    amount      INT NOT NULL,               -- +earn / -spend (negative = locked or spent)
    type        VARCHAR(30) NOT NULL,       -- CHECK_IN | PUBLISH_SKILL | INSTALL | RATING |
                                            -- COMMENT | UPVOTE | READ_NEWS | BOUNTY_LOCK |
                                            -- BOUNTY_AWARD | BOUNTY_REFUND | PERK_REDEEM |
                                            -- STREAK_BONUS | PENALTY
    reason      VARCHAR(300),
    ref_type    VARCHAR(30),                -- SKILL | SKILL_REQUEST | PERK | ...
    ref_id      BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_points_tx_user_time ON points_transactions (user_id, created_at DESC);
CREATE INDEX idx_points_tx_type_time ON points_transactions (type, created_at);

CREATE TABLE daily_checkins (
    user_id      BIGINT NOT NULL REFERENCES "user"(id),
    checkin_date DATE NOT NULL,
    streak       INT NOT NULL DEFAULT 1,    -- consecutive-day streak ending on this date
    created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, checkin_date)
);

CREATE TABLE perks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL UNIQUE,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    cost        INT NOT NULL CHECK (cost > 0),
    active      CHAR(1) NOT NULL DEFAULT 'Y' CHECK (active IN ('Y', 'N'))
);

CREATE TABLE perk_redemptions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES "user"(id),
    perk_id     BIGINT NOT NULL REFERENCES perks(id),
    cost        INT NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',  -- ACTIVE | USED | EXPIRED
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  TIMESTAMPTZ
);

CREATE INDEX idx_perk_redemptions_user ON perk_redemptions (user_id, created_at DESC);

