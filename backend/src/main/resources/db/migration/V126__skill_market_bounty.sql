-- V126: Skill Market bounty (treo thưởng) on skill_requests.
-- Decided 2026-11-16 (from Stack Overflow / Bountysource / Gitcoin behaviour):
--  - the requester decides; NO admin in the main flow (dispute is the exception);
--  - bounty points are locked (escrow) at posting, released on accept,
--    auto-awarded when the requester stays silent past the decision deadline,
--    refunded when the bounty expires with no qualifying claim;
--  - two ways to fulfil: BUILD a new skill (100%) or MATCH an existing skill
--    (70% skill author / 30% referrer; referring your own skill = 100%);
--  - the ONLY ban is claiming your own request's bounty.

ALTER TABLE skill_requests ADD COLUMN bounty_points INT NOT NULL DEFAULT 0 CHECK (bounty_points >= 0);
ALTER TABLE skill_requests ADD COLUMN bounty_status VARCHAR(20) NOT NULL DEFAULT 'NONE';
-- NONE | ACTIVE | FULFILLED | EXPIRED | REFUNDED
ALTER TABLE skill_requests ADD COLUMN bounty_expires_at TIMESTAMPTZ;
ALTER TABLE skill_requests ADD COLUMN fulfilled_skill_id BIGINT REFERENCES skills_master(id);
ALTER TABLE skill_requests ADD COLUMN fulfilled_by BIGINT REFERENCES "user"(id);
ALTER TABLE skill_requests ADD COLUMN bounty_awarded_at TIMESTAMPTZ;

CREATE INDEX idx_skill_requests_bounty_status ON skill_requests (bounty_status, bounty_expires_at);

CREATE TABLE bounty_claims (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT NOT NULL REFERENCES skill_requests(id),
    skill_id    BIGINT NOT NULL REFERENCES skills_master(id),
    claimant_id BIGINT NOT NULL REFERENCES "user"(id),
    claim_type  VARCHAR(10) NOT NULL CHECK (claim_type IN ('BUILD', 'MATCH')),
    -- BUILD: claimant created the skill; MATCH: claimant refers to an existing skill
    status      VARCHAR(20) NOT NULL DEFAULT 'PENDING',  -- PENDING | ACCEPTED | REJECTED | DISPUTED
    decide_by   TIMESTAMPTZ NOT NULL,       -- claimant created_at + 7 days
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at  TIMESTAMPTZ,
    UNIQUE (request_id, skill_id)
);

CREATE INDEX idx_bounty_claims_request ON bounty_claims (request_id, created_at);
CREATE INDEX idx_bounty_claims_pending ON bounty_claims (status, decide_by);
